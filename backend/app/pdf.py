"""A tiny, valid PDF builder for document downloads.

The Learning Centre's download button must hand back a real, openable file
without a CDN or object storage. This writes a single-page PDF with correct
cross-reference offsets, which every PDF reader accepts.
"""

from __future__ import annotations

from datetime import date

FORUM24_SKY = "0.102 0.467 0.714"  # #1A77B6
INK = "0.118 0.161 0.231"  # #1E293B


def _escape(text: str) -> str:
    safe = text.encode("latin-1", "replace").decode("latin-1")
    return safe.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")


def _wrap(text: str, width: int = 74) -> list[str]:
    words = text.split()
    lines: list[str] = []
    current = ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) > width and current:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return lines or [""]


def build_sample_pdf(title: str, *, publisher: str = "FORUM24 Learning") -> bytes:
    """Return a one-page A4 PDF for ``title`` with a clear sample label."""
    lines = _wrap(title, 48)[:3]
    content: list[str] = [
        "BT",
        f"/F1 24 Tf /F2 11 Tf {FORUM24_SKY} rg",
        "56 770 Td",
    ]

    # Title, one text-showing operator per line.
    content.append(f"/F1 24 Tf {INK} rg")
    for index, line in enumerate(lines):
        if index:
            content.append("0 -30 Td")
        content.append(f"({_escape(line)}) Tj")

    content += [
        "0 -26 Td",
        f"/F2 10 Tf {FORUM24_SKY} rg",
        "(FORUM24 - Learning Centre) Tj",
        "0 -34 Td",
        f"/F2 11 Tf {INK} rg",
        "(Note: this is a sample excerpt generated by the FORUM24 API.) Tj",
        "0 -18 Td",
        "(The full edition is served from object storage in production.) Tj",
        "0 -40 Td",
        f"/F2 12 Tf {INK} rg",
        f"(Publisher: {_escape(publisher)}) Tj",
        "0 -18 Td",
        f"(Downloaded: {date.today().isoformat()}) Tj",
        "ET",
        # Footer rule
        f"{FORUM24_SKY} RG 0.8 w",
        "56 90 m 539 90 l S",
        "BT",
        f"/F2 9 Tf {INK} rg",
        "56 72 Td",
        "(forum24.example  -  Nigeria's pulse. Africa's stories.) Tj",
        "ET",
    ]

    stream = "\n".join(content).encode("latin-1")

    objects: list[bytes] = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        (
            b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
            b"/Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>"
        ),
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(stream)).encode("ascii") + b" >>\nstream\n" + stream + b"\nendstream",
    ]

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets: list[int] = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{number} 0 obj\n".encode("ascii") + body + b"\nendobj\n"

    xref_offset = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("ascii")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("ascii")
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_offset}\n%%EOF\n"
    ).encode("ascii")
    return bytes(out)
